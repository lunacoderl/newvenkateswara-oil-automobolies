/**
 * Helper to fetch service data by slug
 * @param {string} slug
 * @returns {Object|null} Service object if found and published, otherwise null
 */
export function getServiceBySlug(slug) {
  if (!slug) return null;
  const match = SERVICES.find(
    (item) => item.slug.toLowerCase() === slug.toLowerCase() && item.published
  );
  return match || null;
}

/**
 * Helper to get all published services
 * @returns {Array} List of published service objects
 */
export function getPublishedServices() {
  return SERVICES.filter((item) => item.published);
}

/**
 * Helper to get related services for a given slug
 * @param {string} slug
 * @returns {Array} List of related service objects
 */
export function getRelatedServices(slug) {
  const current = getServiceBySlug(slug);
  if (!current || !current.relatedServiceSlugs) return [];
  return current.relatedServiceSlugs
    .map((s) => getServiceBySlug(s))
    .filter(Boolean);
}
